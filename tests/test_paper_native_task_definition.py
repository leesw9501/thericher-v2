@pytest.mark.parametrize("mode", ["handoff", "denials"])
def test_native_task_definition_with_mocked_scheduler(mode: str) -> None:
    pwsh = shutil.which("pwsh")
    if pwsh is None:
        pytest.skip("PowerShell 7 is required for the native task-definition fixture")

    script = HARNESS.replace("__MODULE__", str(MODULE).replace("'", "''")).replace("__MODE__", mode)
    encoded = base64.b64encode(script.encode("utf-16-le")).decode("ascii")
    result = subprocess.run(
        [pwsh, "-NoLogo", "-NoProfile", "-NonInteractive", "-EncodedCommand", encoded],
        capture_output=True,
        encoding="utf-8",
        check=False,
        timeout=30,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert result.stdout.strip() == "PASS", result.stdout + result.stderr
